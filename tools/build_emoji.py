def build():
    seen, out = set(), []
    for char, name, aliases, category in TABLE:
        if char in seen:
            raise SystemExit(f"дубликат символа: {char} ({name})")
        seen.add(char)
        out.append({
            "char": char,
            "name": name,
            "aliases": aliases,
            "category": category,
        })
    return out


def main():
    data = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(data, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    print(f"{len(data)} символов → {OUT}")


if __name__ == "__main__":
    main()
